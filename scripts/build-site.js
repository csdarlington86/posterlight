'use strict';
// Builds the public website into docs/, which GitHub Pages serves.
//   docs/index.html   the landing page (from site/)
//   docs/demo/        the real poster page with canned data, so it runs with no helper
// Run it with: npm run site
var fs = require('fs');
var path = require('path');
var demo = require('../lib/demo');

var ROOT = path.join(__dirname, '..');
var PUBLIC = path.join(ROOT, 'public');
// The screens the demo walks through, and how long each one stays.
var TOUR = ['movie', 'movie-fact-full', 'tv', 'music', 'intermission'];
var SCREEN_MS = 10000;
// The setup page talks to a helper, so it has no place in the static demo.
var SKIP = { 'setup.html': true, 'setup.js': true, 'setup.css': true };

function copyDir(from, to) {
  fs.mkdirSync(to, { recursive: true });
  fs.readdirSync(from, { withFileTypes: true }).forEach(function (entry) {
    if (SKIP[entry.name] || entry.name === '.DS_Store') return;
    var src = path.join(from, entry.name);
    var dest = path.join(to, entry.name);
    if (entry.isDirectory()) copyDir(src, dest);
    else fs.copyFileSync(src, dest);
  });
}

// The data file is plain ES5, like the page that loads it.
function demoScript() {
  var statuses = {};
  demo.demoNames.forEach(function (name) { statuses[name] = demo.demoStatus(name); });
  return '/* Generated by scripts/build-site.js. Canned data for the public demo: no helper, no Plex. */\n' +
    '(function () {\n' +
    '  var statuses = ' + JSON.stringify(statuses) + ';\n' +
    '  var tour = ' + JSON.stringify(TOUR) + ';\n' +
    '  var screenMs = ' + SCREEN_MS + ';\n' +
    '  var match = /[?&]demo=([a-z-]+)/.exec(location.search || "");\n' +
    '  var fixed = match && Object.prototype.hasOwnProperty.call(statuses, match[1]) ? match[1] : null;\n' +
    '  window.PosterLightDemo = {\n' +
    '    // elapsedMs: time since the page opened. With ?demo=<name> one screen stays; otherwise the tour runs.\n' +
    '    status: function (elapsedMs) {\n' +
    '      if (fixed) return statuses[fixed];\n' +
    '      return statuses[tour[Math.floor(elapsedMs / screenMs) % tour.length]];\n' +
    '    }\n' +
    '  };\n' +
    '})();\n';
}

function build(outDir) {
  fs.mkdirSync(outDir, { recursive: true });
  fs.copyFileSync(path.join(ROOT, 'site', 'index.html'), path.join(outDir, 'index.html'));
  fs.copyFileSync(path.join(ROOT, 'site', 'site.css'), path.join(outDir, 'site.css'));
  fs.writeFileSync(path.join(outDir, '.nojekyll'), '');   // serve the files as they are

  var demoDir = path.join(outDir, 'demo');
  fs.rmSync(demoDir, { recursive: true, force: true });
  copyDir(PUBLIC, demoDir);
  fs.writeFileSync(path.join(demoDir, 'js', 'demo-static.js'), demoScript());
  var page = fs.readFileSync(path.join(demoDir, 'index.html'), 'utf8');
  var marker = '<script src="js/app.js"></script>';
  if (page.indexOf(marker) === -1) throw new Error('public/index.html no longer loads js/app.js the expected way');
  fs.writeFileSync(path.join(demoDir, 'index.html'),
    page.replace(marker, '<script src="js/demo-static.js"></script>\n' + marker));
}

module.exports = { build: build };

if (require.main === module) {
  build(path.join(ROOT, 'docs'));
  console.log('Website written to docs/');
}
