'use strict';
// Builds the public website. GitHub builds and publishes it on every push to main
// (.github/workflows/pages.yml). To build it yourself: npm run site  (writes _site/)
//
//   index.html   the landing page (from site/)
//   app/         the web app: the poster page plus an engine that talks to Plex from the browser
//   demo/        the poster page with canned data, for a look without signing in
var fs = require('fs');
var path = require('path');
var demo = require('../lib/demo');

var ROOT = path.join(__dirname, '..');
var PUBLIC = path.join(ROOT, 'public');
var LIB = path.join(ROOT, 'lib');
var SITE = path.join(ROOT, 'site');
// The screens the demo walks through, and how long each one stays.
var TOUR = ['movie', 'tv', 'music', 'intermission'];
var SCREEN_MS = 10000;
// The helper's own setup page talks to a helper, so it is not part of the website.
var SKIP = { 'setup.html': true, 'setup.js': true, 'setup.css': true };
// The helper modules the browser engine needs, in any order.
var WEB_MODULES = ['plex-parser', 'session-tracker', 'status', 'web-engine', 'web-connect'];
var APP_MARKER = '<script src="js/app.js"></script>';

function copyDir(from, to) {
  fs.mkdirSync(to, { recursive: true });
  fs.readdirSync(from, { withFileTypes: true }).forEach(function (entry) {
    if (SKIP[entry.name] || entry.name.charAt(0) === '.') return;
    var src = path.join(from, entry.name);
    var dest = path.join(to, entry.name);
    if (entry.isDirectory()) copyDir(src, dest);
    else fs.copyFileSync(src, dest);
  });
}

function injectBefore(page, scripts) {
  if (page.indexOf(APP_MARKER) === -1) throw new Error('public/index.html no longer loads js/app.js the expected way');
  var tags = scripts.map(function (s) { return '<script src="' + s + '"></script>'; }).join('\n');
  return page.replace(APP_MARKER, tags + '\n' + APP_MARKER);
}

// ---- demo ----

function demoScript() {
  var statuses = {};
  demo.demoNames.forEach(function (name) { statuses[name] = demo.demoStatus(name); });
  return '/* Generated by scripts/build-site.js. Canned data for the public demo: no helper, no Plex. */\n' +
    '(function () {\n' +
    '  var statuses = ' + JSON.stringify(statuses) + ';\n' +
    '  var tour = ' + JSON.stringify(TOUR) + ';\n' +
    '  var screenMs = ' + SCREEN_MS + ';\n' +
    '  var opened = new Date().getTime();\n' +
    '  var match = /[?&]demo=([a-z-]+)/.exec(location.search || "");\n' +
    '  var fixed = match && Object.prototype.hasOwnProperty.call(statuses, match[1]) ? match[1] : null;\n' +
    '  // With ?demo=<name> one screen stays. Otherwise the tour runs.\n' +
    '  function statusAt(elapsedMs) {\n' +
    '    if (fixed) return statuses[fixed];\n' +
    '    return statuses[tour[Math.floor(elapsedMs / screenMs) % tour.length]];\n' +
    '  }\n' +
    '  window.PosterLightLocal = {\n' +
    '    demo: true,\n' +
    '    statusAt: statusAt,\n' +
    '    status: function () { return statusAt(new Date().getTime() - opened); },\n' +
    '    players: function () { return []; },\n' +
    '    imageUrl: function (id) { return "demo/" + encodeURIComponent(id) + ".svg"; }\n' +
    '  };\n' +
    '})();\n';
}

function buildDemo(dir) {
  fs.rmSync(dir, { recursive: true, force: true });
  copyDir(PUBLIC, dir);
  fs.writeFileSync(path.join(dir, 'js', 'demo-static.js'), demoScript());
  var page = fs.readFileSync(path.join(dir, 'index.html'), 'utf8');
  fs.writeFileSync(path.join(dir, 'index.html'), injectBefore(page, ['js/demo-static.js']));
}

// ---- web app ----

// Wraps the helper's CommonJS modules so a browser can load them as one plain script.
function webBundle() {
  var out = '/* Generated by scripts/build-site.js from lib/. Do not edit: change the files in lib/ instead. */\n' +
    '(function () {\n' +
    'var defs = {}, loaded = {};\n' +
    'function load(name) {\n' +
    '  name = name.replace("./", "");\n' +
    '  if (!loaded[name]) { loaded[name] = { exports: {} }; defs[name](loaded[name], loaded[name].exports, load); }\n' +
    '  return loaded[name].exports;\n' +
    '}\n';
  WEB_MODULES.forEach(function (name) {
    out += 'defs["' + name + '"] = function (module, exports, require) {\n' +
      fs.readFileSync(path.join(LIB, name + '.js'), 'utf8') + '\n};\n';
  });
  out += 'window.PosterLightWeb = {\n' +
    '  createWebEngine: load("web-engine").createWebEngine,\n' +
    '  createWebConnect: load("web-connect").createWebConnect\n' +
    '};\n})();\n';
  return out + fs.readFileSync(path.join(SITE, 'web-runtime.js'), 'utf8');
}

function buildApp(dir) {
  fs.rmSync(dir, { recursive: true, force: true });
  copyDir(PUBLIC, dir);
  fs.copyFileSync(path.join(PUBLIC, 'css', 'setup.css'), path.join(dir, 'css', 'setup.css'));   // styles the connect screen
  fs.writeFileSync(path.join(dir, 'js', 'posterlight-web.js'), webBundle());
  fs.copyFileSync(path.join(SITE, 'app-boot.js'), path.join(dir, 'js', 'app-boot.js'));
  fs.copyFileSync(path.join(SITE, 'connect.js'), path.join(dir, 'js', 'connect.js'));
  fs.copyFileSync(path.join(SITE, 'connect.html'), path.join(dir, 'connect.html'));
  var page = fs.readFileSync(path.join(dir, 'index.html'), 'utf8');
  fs.writeFileSync(path.join(dir, 'index.html'), injectBefore(page, ['js/posterlight-web.js', 'js/app-boot.js']));
}

function build(outDir) {
  fs.mkdirSync(outDir, { recursive: true });
  fs.copyFileSync(path.join(SITE, 'index.html'), path.join(outDir, 'index.html'));
  fs.copyFileSync(path.join(SITE, 'site.css'), path.join(outDir, 'site.css'));
  var shot = path.join(ROOT, 'docs', 'screenshot.jpg');
  if (fs.existsSync(shot)) fs.copyFileSync(shot, path.join(outDir, 'screenshot.jpg'));
  fs.writeFileSync(path.join(outDir, '.nojekyll'), '');   // serve the files as they are
  buildDemo(path.join(outDir, 'demo'));
  buildApp(path.join(outDir, 'app'));
}

module.exports = { build: build };

if (require.main === module) {
  var target = path.resolve(process.argv[2] || path.join(ROOT, '_site'));
  build(target);
  console.log('Website written to ' + target);
}
